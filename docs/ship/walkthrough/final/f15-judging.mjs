// Sponsor · Judging (Sun Life, fake teams from sponsor-picks.ts --teams 15).
// Scores are cleared for Sun Life first. Seed reps (Dana W., Kevin T.) judge.
import { open, snap, say, wait, close, BASE, SPONSORS, sql, clean } from "./lib-final.mjs";

const SL = SPONSORS.sunlife;
sql(`delete from sponsor_team_score where sponsor_id='${SL}'; delete from sponsor_shortlist_send where sponsor_id='${SL}';`);
const W = Number(process.argv[2] || 1280);
const tag = W === 1280 ? "" : "-390";
const { page } = await open(W);
const main = page.locator("#sponsor-main");
const lines = async (re, n = 8) => clean(await main.innerText()).split("\n").filter((l) => re.test(l)).slice(0, n).join(" / ");

say("Without ?preview=judging. EXPECT 'Judging opens Sunday 9:00 AM'");
await page.goto(`${BASE}/sponsors/${SL}/picks`, { waitUntil: "networkidle", timeout: 120000 });
await wait(page, 1500);
console.log(await lines(/Judging opens/));
await page.goto(`${BASE}/sponsors/${SL}/picks?preview=judging`, { waitUntil: "networkidle" });
await wait(page, 1500);
say("Who's judging? EXPECT 'Your team reps' + 'Someone else'");
console.log(clean(await main.innerText()).slice(0, 500));
await snap(page, `f15-whos-judging${tag}`);
await main.getByRole("button", { name: /Dana W\./ }).first().click();
await wait(page, 400);
const start = main.getByRole("button", { name: "Start judging" });
if (await start.count()) await start.click();
await wait(page, 1200);
const strip = page.getByRole("slider").first();
say("Dana scores. EXPECT strip 1–10 in half points, dimmed until touched; End then Left = 9.5");
console.log("strip before:", await strip.getAttribute("aria-valuetext"));
await strip.focus();
await page.keyboard.press("End");
await page.keyboard.press("ArrowLeft");
await wait(page, 1500);
console.log("strip after:", await strip.getAttribute("aria-valuetext"));
console.log(await lines(/Judging as|Your \d|Everyone's|of \d+/));
await snap(page, `f15-scored${tag}`);
say("Rubric");
await page.getByRole("button", { name: /rubric/i }).first().click();
await wait(page, 600);
console.log("rubric:", clean(await page.getByRole("dialog").innerText().catch(() => "(none)")).replace(/\s+/g, " ").slice(0, 300));
await page.keyboard.press("Escape");
say("Kevin T. scores the same team 6 (two reps split the list 'Your N' / 'Everyone's N'). EXPECT 'Dana 9.5 · Kevin 6', average, amber flag");
const team = clean(await main.innerText()).match(/\n([^\n]+)\nTeam|Judging as[^\n]*\n([^\n]+)/)?.[0];
await page.getByRole("button", { name: /Switch who's judging/ }).click();
await page.getByRole("button", { name: /Kevin T\./ }).first().click();
const st2 = main.getByRole("button", { name: "Start judging" });
if (await st2.count()) await st2.click();
await wait(page, 800);
console.log("split:", await lines(/^Your \d|^Everyone's/));
await page.getByRole("button", { name: /^Everyone's/ }).or(page.getByRole("tab", { name: /^Everyone's/ })).first().click().catch(() => console.log("no Everyone's"));
await wait(page, 600);
const s2 = page.getByRole("slider").first();
await s2.focus();
await page.keyboard.press("Home");
for (let i = 0; i < 10; i++) await page.keyboard.press("ArrowRight");
await wait(page, 1500);
console.log("Kevin:", await s2.getAttribute("aria-valuetext"));
console.log(await lines(/Dana|Kevin|avg|Average|apart|talk/i));
await snap(page, `f15-two-reps${tag}`);
say("Shortlist tab + send. EXPECT a send button (empty shortlist explained)");
await page.getByRole("tab", { name: /shortlist/i }).first().click().catch(() => console.log("no shortlist tab"));
await wait(page, 800);
console.log(await lines(/shortlist|Send|empty/i, 10));
const add = main.getByRole("button", { name: /^(Add to shortlist|Shortlist)/ });
console.log("add buttons:", await add.count());
const send = main.getByRole("button", { name: /^Send/ });
console.log("send buttons:", await send.count(), (await send.allInnerTexts()).join(" | "));
await snap(page, `f15-shortlist${tag}`);
console.log("errors:", page.errors.filter((e) => !/%c/.test(e)).slice(0, 5));
console.log("DB scores:", sql(`select judge_name, score from sponsor_team_score where sponsor_id='${SL}'`).trim().replace(/\n/g, ", "));
await close();
