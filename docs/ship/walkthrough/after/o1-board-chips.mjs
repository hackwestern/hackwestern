// After: board chips (B3), digital sponsors (B2), walk note (B8).
import { open, wait, close, BASE, USERS, shotAfter } from "./lib-after.mjs";
const W = Number(process.argv[2] || 1280);
const tag = W === 1280 ? "" : "-390";
const { page } = await open(W, USERS.organizer);
await page.goto(`${BASE}/internal/sponsors?tab=coffee`, { waitUntil: "networkidle", timeout: 180000 });
await page.waitForSelector("text=Suggested fixes", { timeout: 180000 });
const nt = page.getByRole("button", { name: "No thanks" });
if (await nt.count()) await nt.first().click();
await wait(page, 1500);
const labels = await page.locator("button[aria-expanded]").evaluateAll((b) => b.map((x) => x.getAttribute("aria-label") || ""));
console.log("rows:", labels.filter(Boolean).join(" | "));
console.log("PCBWay on board:", labels.some((l) => /PCBWay/.test(l)));
const summary = await page.locator('section[aria-label="Since last time"] p').first().innerText();
console.log("summary:", summary);
await shotAfter(page, `o1-board-chips${tag}`);
const row = page.getByRole("button", { name: /^Test Sponsor,/ });
await row.click();
await wait(page, 800);
await row.scrollIntoViewIfNeeded();
const body = await page.locator("body").innerText();
console.log("walk notes:", body.split("\n").filter((l) => /Walk (to|back)/.test(l)).join(" / ") || "(none)");
await shotAfter(page, `o1-board-test-sponsor-row${tag}`);
console.log("errors:", page.errors.filter((e) => !/%c/.test(e)).slice(0, 5));
await close();
