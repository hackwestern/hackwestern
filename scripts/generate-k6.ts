/**
 * Generates a k6 smoke test from `src/generated/app.json`.
 *
 *   npm run k6:generate [-- --profile traffic-profile.json]
 *   k6 run -e BASE_URL=http://localhost:3000 k6/smoke.generated.js
 *
 * BASE_URL is required (no default) and production is refused unless
 * ALLOW_PROD=1, so a smoke test can never hit the live site by accident.
 *
 * Safe by construction: only GET pages, public GET REST routes and tRPC
 * *queries* that need no input are targeted. Mutations, organizer and judge
 * procedures are never included. Authenticated read-only queries are added only
 * when `K6_AUTH_COOKIE` is passed to k6 at run time.
 *
 * With a traffic profile (see build-traffic-profile.ts) requests are weighted
 * by real usage; without one every target is equally likely.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const APP_JSON = path.join(ROOT, "src/generated/app.json");
const OUT = path.join(ROOT, "k6/smoke.generated.js");

/** Pages that are public but have side effects or need params/tokens. */
const SKIP_PAGES =
  /logout|verify|reset-password|unsubscribe|wallet|scan|redeem|\[/;

interface Target {
  name: string;
  kind: "page" | "rest" | "trpc";
  url: string;
  auth: boolean;
  weight: number;
}

interface AppMap {
  trpc: { path: string; type: string; auth: string; input: unknown }[];
  rest: { route: string; methods: string[]; auth: string[] }[];
  pages: {
    route: string;
    auth: string;
    serverGuards: string[];
    dynamic: boolean;
  }[];
}

const profileArg = process.argv.indexOf("--profile");
const profile: { routes?: Record<string, number> } =
  profileArg > -1
    ? JSON.parse(fs.readFileSync(process.argv[profileArg + 1]!, "utf8"))
    : {};
const weightOf = (name: string) =>
  profile.routes?.[name] ?? (profile.routes ? 0.01 : 1);

const map = JSON.parse(fs.readFileSync(APP_JSON, "utf8")) as AppMap;
const targets: Target[] = [];

for (const p of map.pages) {
  if (p.dynamic || SKIP_PAGES.test(p.route) || p.serverGuards.length) continue;
  targets.push({
    name: p.route,
    kind: "page",
    url: p.route,
    auth: false,
    weight: weightOf(p.route),
  });
}

for (const r of map.rest) {
  const open = r.auth.length === 1 && r.auth[0] === "none-detected";
  if (open && r.methods.includes("GET") && !r.route.includes("[")) {
    targets.push({
      name: r.route,
      kind: "rest",
      url: r.route,
      auth: false,
      weight: weightOf(r.route),
    });
  }
}

for (const t of map.trpc) {
  if (t.type !== "query" || t.input !== null) continue;
  if (t.auth !== "public" && t.auth !== "protected") continue;
  targets.push({
    name: t.path,
    kind: "trpc",
    url: `/api/trpc/${t.path}`,
    auth: t.auth === "protected",
    weight: weightOf(t.path),
  });
}

const script = `// GENERATED by scripts/generate-k6.ts from src/generated/app.json. Do not edit.
import http from "k6/http";
import { check, sleep } from "k6";

const BASE_URL = (__ENV.BASE_URL || "").replace(/\\/$/, "");
if (!BASE_URL) {
  throw new Error("Set BASE_URL, e.g. -e BASE_URL=http://localhost:3000 (dev/preview). There is no default on purpose.");
}
if (/^https?:\\/\\/(www\\.)?hackwestern\\.com/.test(BASE_URL) && __ENV.ALLOW_PROD !== "1") {
  throw new Error("Refusing to load-test production. Pass -e ALLOW_PROD=1 if you really mean it.");
}
const COOKIE = __ENV.K6_AUTH_COOKIE || "";
const VUS = Number(__ENV.VUS || 5);
const DURATION = __ENV.DURATION || "30s";

const ALL_TARGETS = ${JSON.stringify(targets, null, 2)};
const TARGETS = ALL_TARGETS.filter((t) => !t.auth || COOKIE);
const TOTAL = TARGETS.reduce((n, t) => n + t.weight, 0);

export const options = {
  scenarios: {
    smoke: { executor: "constant-vus", vus: VUS, duration: DURATION },
  },
  thresholds: {
    http_req_failed: ["rate<0.01"],
    http_req_duration: ["p(95)<1500"],
    checks: ["rate>0.99"],
  },
};

function pick() {
  let r = Math.random() * TOTAL;
  for (const t of TARGETS) {
    r -= t.weight;
    if (r <= 0) return t;
  }
  return TARGETS[TARGETS.length - 1];
}

export default function () {
  const t = pick();
  const params = {
    headers: COOKIE && t.auth ? { Cookie: COOKIE } : {},
    tags: { name: t.name, kind: t.kind },
  };
  const res = http.get(BASE_URL + t.url, params);
  check(res, {
    [t.name + " status 200"]: (r) => r.status === 200,
    [t.name + " trpc result"]: (r) => t.kind !== "trpc" || r.json("result") !== undefined,
  });
  sleep(0.5 + Math.random());
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, script);
const by = (k: Target["kind"]) => targets.filter((t) => t.kind === k).length;
console.log(
  `Wrote ${path.relative(ROOT, OUT)}: ${by("page")} pages, ${by("rest")} REST, ${by("trpc")} tRPC queries (${targets.filter((t) => t.auth).length} need K6_AUTH_COOKIE)${profileArg > -1 ? ", weighted by profile" : ""}.`,
);
